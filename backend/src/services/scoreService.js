import prisma from '../utils/prisma.js';

const MAX_SCORE = 10;
const MIN_SCORE = 0;
const INITIAL_SCORE = 8.0;
const ANOTACOES_TO_TMD = parseInt(process.env.ANOTACOES_TO_TMD || '4');

/**
 * Aplica delta na nota do aluno, respeitando limites [0, 10]
 * Registra histórico e atualiza currentScore
 */
export async function applyScoreChange({
  studentId,
  delta,
  reason,
  occurrenceId = null,
  praiseId = null,
}) {
  return prisma.$transaction(async (tx) => {
    const student = await tx.student.findUnique({ where: { id: studentId } });
    if (!student) throw new Error('Aluno não encontrado');

    const previousScore = student.currentScore;
    let newScore = previousScore + delta;

    // Clamp [0, 10]
    if (newScore > MAX_SCORE) newScore = MAX_SCORE;
    if (newScore < MIN_SCORE) newScore = MIN_SCORE;

    const realDelta = newScore - previousScore;

    await tx.student.update({
      where: { id: studentId },
      data: { currentScore: newScore },
    });

    await tx.scoreHistory.create({
      data: {
        studentId,
        previousScore,
        newScore,
        delta: realDelta,
        reason,
        occurrenceId,
        praiseId,
      },
    });

    return { previousScore, newScore, delta: realDelta };
  });
}

// Ordem crescente de gravidade
const NATUREZA_ORDER = { LEVE: 0, MEDIA: 1, GRAVE: 2, GRAVISSIMO: 3 };

// Número do artigo → natureza (conforme regimento CMTO)
const ARTIGO_NATUREZA = { 104: 'LEVE', 105: 'MEDIA', 106: 'GRAVE', 107: 'GRAVISSIMO' };

function naturezaDaAnotacao(anotacao) {
  // 1. Categoria com defaultLevel definido
  if (anotacao.category?.defaultLevel && NATUREZA_ORDER[anotacao.category.defaultLevel] !== undefined) {
    return anotacao.category.defaultLevel;
  }
  // 2. Prefixo de artigo na descrição: "[Art. 106, inc. XLIX] ..."
  const match = anotacao.description.match(/\[Art\.\s*(\d+)/i);
  if (match) {
    const nat = ARTIGO_NATUREZA[parseInt(match[1])];
    if (nat) return nat;
  }
  // 3. Padrão
  return 'LEVE';
}

function maiorNatureza(anotacoes) {
  return anotacoes.reduce((max, a) => {
    const nat = naturezaDaAnotacao(a);
    return NATUREZA_ORDER[nat] > NATUREZA_ORDER[max] ? nat : max;
  }, 'LEVE');
}

/**
 * Verifica se o aluno acumulou N anotações pendentes.
 * Se sim, gera automaticamente um TMD no nível da maior natureza entre as anotações.
 */
export async function checkAndGenerateAutoTMD(studentId, userId) {
  const pendingAnotacoes = await prisma.occurrence.findMany({
    where: {
      studentId,
      type: 'ANOTACAO',
      status: { in: ['APROVADO', 'ARQUIVADO'] }, // arquivadas continuam contando
      autoGenerated: false,
    },
    include: { category: true },
    orderBy: { createdAt: 'asc' },
  });

  // Filtrar anotações já consumidas por algum TMD auto-gerado anterior
  const alreadyConsumed = await prisma.occurrence.findMany({
    where: { studentId, autoGenerated: true, generatedFromIds: { not: null } },
    select: { generatedFromIds: true },
  });

  const consumedSet = new Set();
  alreadyConsumed.forEach(o => {
    o.generatedFromIds.split(',').forEach(id => consumedSet.add(id));
  });

  const available = pendingAnotacoes.filter(a => !consumedSet.has(a.id));

  if (available.length < ANOTACOES_TO_TMD) return null;

  const consumed = available.slice(0, ANOTACOES_TO_TMD);
  const consumedIds = consumed.map(c => c.id).join(',');

  // Determinar nível pelo maior natureza das anotações
  const tmdLevel = maiorNatureza(consumed);
  const scoreImpact = SCORE_RANGES[`TMD_${tmdLevel}`].default;

  const TMD_LEVEL_LABELS = {
    LEVE: 'Leve', MEDIA: 'Médio', GRAVE: 'Grave', GRAVISSIMO: 'Gravíssimo',
  };

  const autoTMD = await prisma.occurrence.create({
    data: {
      studentId,
      type: 'TMD',
      tmdLevel,
      occurredAt: new Date(),
      description: `TMD ${TMD_LEVEL_LABELS[tmdLevel]} gerado automaticamente pelo acúmulo de ${ANOTACOES_TO_TMD} anotações.`,
      scoreImpact,
      status: 'AUTO_GERADO',
      autoGenerated: true,
      generatedFromIds: consumedIds,
      createdById: userId,
    },
  });

  await applyScoreChange({
    studentId,
    delta: scoreImpact,
    reason: `TMD ${TMD_LEVEL_LABELS[tmdLevel]} automático (acúmulo de ${ANOTACOES_TO_TMD} anotações)`,
    occurrenceId: autoTMD.id,
  });

  return autoTMD;
}

/**
 * Verifica se o aluno cruzou limites de alerta e cria notificações
 */
export async function checkScoreAlerts(studentId) {
  const config = await getConfig();
  const student = await prisma.student.findUnique({
    where: { id: studentId },
    include: { class: true },
  });

  if (!student) return;

  const alerts = [];

  if (student.currentScore < config.criticalThreshold) {
    alerts.push({
      type: 'ALERTA_CRITICO',
      title: `🚨 Aluno em nível CRÍTICO`,
      message: `${student.name} (${student.class.name}) está com conceito ${student.currentScore.toFixed(2)}.`,
    });
  } else if (student.currentScore < config.attentionThreshold) {
    alerts.push({
      type: 'ALERTA_ATENCAO',
      title: `⚠️ Aluno em atenção`,
      message: `${student.name} (${student.class.name}) está com conceito ${student.currentScore.toFixed(2)}.`,
    });
  }

  // Notificar admins e coords
  if (alerts.length > 0) {
    const recipients = await prisma.user.findMany({
      where: {
        active: true,
        role: { in: ['ADMIN', 'COORD_DISCIPLINAR', 'COORD_PEDAGOGICO'] },
      },
      select: { id: true },
    });

    for (const alert of alerts) {
      for (const r of recipients) {
        await prisma.notification.create({
          data: {
            userId: r.id,
            type: alert.type,
            title: alert.title,
            message: alert.message,
            link: `/students/${studentId}`,
          },
        });
      }
    }
  }

  return alerts;
}

export async function getConfig() {
  const configs = await prisma.systemConfig.findMany();
  const map = {};
  configs.forEach(c => { map[c.key] = c.value; });

  return {
    initialScore: parseFloat(map.initialScore || INITIAL_SCORE),
    attentionThreshold: parseFloat(map.attentionThreshold || process.env.DEFAULT_ATTENTION_THRESHOLD || 6.5),
    criticalThreshold: parseFloat(map.criticalThreshold || process.env.DEFAULT_CRITICAL_THRESHOLD || 5.0),
    anotacoesToTMD: parseInt(map.anotacoesToTMD || ANOTACOES_TO_TMD),
    cycleType: map.cycleType || 'ANUAL',
    emailNotifications: map.emailNotifications === 'true',
  };
}

/**
 * Faixas de impacto por tipo
 */
export const SCORE_RANGES = {
  TMD_LEVE: { min: -0.40, max: -0.20, default: -0.30 },
  TMD_MEDIA: { min: -0.60, max: -0.40, default: -0.50 },
  TMD_GRAVE: { min: -1.00, max: -0.60, default: -0.80 },
  TMD_GRAVISSIMO: { min: -2.00, max: -1.00, default: -1.50 },
  PRAISE_COLETIVO: { min: 0.20, max: 0.39, default: 0.30 },
  PRAISE_INDIVIDUAL: { min: 0.40, max: 0.59, default: 0.50 },
  PRAISE_MENCAO: { min: 0.60, max: 1.00, default: 0.80 },
};

export function validateScoreImpact(type, level, value) {
  let range;
  if (type === 'TMD') {
    range = SCORE_RANGES[`TMD_${level}`];
  } else if (type === 'PRAISE') {
    range = SCORE_RANGES[`PRAISE_${level}`];
  }
  if (!range) return true;
  return value >= range.min && value <= range.max;
}
